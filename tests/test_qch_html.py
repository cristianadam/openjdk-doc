class TestPreprocessHtml(unittest.TestCase):

    def setUp(self):
        page, self.converted = qch_html.preprocess_html(PAGE, 'css/x.css')
        self.page = page
        self.document = html.document_fromstring(page)

    def test_links_the_generated_stylesheet_and_nothing_else(self):
        links = [element.get('href')
                 for element in self.document.iter('link')]
        self.assertEqual(['css/x.css'], links)

    def test_keeps_the_title(self):
        self.assertEqual('String (Java SE 25)',
                         self.document.find('.//title').text)

    def test_drops_what_only_a_script_could_drive(self):
        for tag in ('script', 'noscript', 'button', 'input'):
            self.assertEqual([], list(self.document.iter(tag)), tag)

        for name in ('top-nav', 'nav-list-search', 'skip-nav', 'table-tabs'):
            self.assertEqual([], qch_html.by_class(self.document, name), name)

    def test_drops_the_in_page_contents(self):
        self.assertEqual([], qch_html.by_class(self.document, 'toc', 'nav'))

    def test_keeps_the_breadcrumb_at_the_top_of_the_content(self):
        main = self.document.find('.//main')
        self.assertEqual('ol', main[0].tag)
        self.assertIn('sub-nav-list', main[0].get('class'))

    def test_drops_the_emptied_navigation_elements(self):
        self.assertEqual([], list(self.document.iter('header')))
        self.assertEqual([], list(self.document.iter('nav')))

    def test_unwraps_the_grid_that_laid_out_the_content(self):
        self.assertEqual([], qch_html.by_class(self.document, 'main-grid'))

    def test_rebuilds_the_summary_table(self):
        self.assertEqual(1, self.converted)

        tables = self.document.findall('.//table')
        self.assertEqual(1, len(tables))
        self.assertIn('summary-table', tables[0].get('class'))

        headers = tables[0].findall('.//thead/tr/th')
        self.assertEqual(['Modifier and Type', 'Method', 'Description'],
                         [cell.text_content() for cell in headers])

        rows = tables[0].findall('.//tbody/tr')
        self.assertEqual(1, len(rows))
        self.assertEqual(3, len(rows[0]))
        self.assertEqual('td', rows[0][0].tag)
        self.assertEqual('char', rows[0][0].text_content())

    def test_keeps_the_column_classes_and_drops_the_tab_ones(self):
        cell = self.document.findall('.//tbody/tr')[0][0]
        classes = cell.get('class').split()
        self.assertIn('col-first', classes)
        self.assertIn('even-row-color', classes)
        self.assertEqual([name for name in classes if 'summary-table' in name],
                         [])

    def test_a_cell_holds_the_signature_in_one_piece(self):
        cell = self.document.findall('.//tbody/tr')[0][1]
        self.assertEqual([], list(cell.iter('wbr')))
        self.assertIn('charAt', cell.text_content())

    def test_drops_the_comments(self):
        self.assertNotIn('<!--', self.page)


class TestColumnCount(unittest.TestCase):

    def count(self, class_name):
        element = html.fragment_fromstring('<div class="%s"></div>'
                                           % class_name)
        return qch_html.column_count(element)

    def test_reads_the_count_out_of_the_class(self):
        self.assertEqual(2, self.count('summary-table two-column-summary'))
        self.assertEqual(3, self.count('summary-table three-column-summary'))
        self.assertEqual(4, self.count('summary-table four-column-summary'))

    def test_reads_the_release_summary_as_three_columns(self):
        self.assertEqual(
            3, self.count('summary-table three-column-release-summary'))

    def test_a_table_that_names_no_count_is_left_alone(self):
        self.assertIsNone(self.count('summary-table'))


class TestUnwrap(unittest.TestCase):

    def unwrapped(self, source, tag):
        document = html.fragment_fromstring(source)
        for element in list(document.iter(tag)):
            qch_html.unwrap(element)
        return html.tostring(document, encoding='unicode')

    def test_keeps_the_text_around_what_it_removes(self):
        self.assertEqual('<p>one two three</p>',
                         self.unwrapped('<p>one <b>two</b> three</p>', 'b'))

    def test_keeps_the_text_of_an_element_that_opens_the_line(self):
        self.assertEqual('<p>one two</p>',
                         self.unwrapped('<p><b>one</b> two</p>', 'b'))

    def test_keeps_what_the_element_held(self):
        self.assertEqual('<p>a <i>b</i> c</p>',
                         self.unwrapped('<p>a <b><i>b</i></b> c</p>', 'b'))


